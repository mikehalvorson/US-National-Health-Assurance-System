/* src/lib/manifest-check.ts -> repo root */
const REPO_ROOT = fileURLToPath(new URL('../..', import.meta.url));

export const MANIFEST_ROOTS = ['src', 'tools', 'research'];

/* Not source, and regenerated by anyone who runs a tools/*.py generator, so
   listing it would make the manifest drift on every run. Mirrors .gitignore. */
const IGNORED_DIRS = new Set(['__pycache__']);

/* Memoised per root. These run inside self-tests, which vitest re-imports once
   per test file; without the cache the suite spends minutes re-walking the tree
   and re-reading a 119 KB catalog. */
const fileCache = new Map<string, string[]>();

export function enumerateSourceFiles(root = REPO_ROOT): string[] {
  const hit = fileCache.get(root);
  if (hit) return hit;
  const out: string[] = [];
  for (const dir of MANIFEST_ROOTS) walk(join(root, dir), root, out);
  out.sort();
  fileCache.set(root, out);
  return out;
}

/* Code review [§S9a]: the same memoisation, for raw file text.
 *
 * §S9a added twelve checks that read markdown and source as text, each with
 * its own `readFileSync`. Four of them re-read the same 20 KB methodology
 * note and two re-read the framework transcription, once per self-test pass,
 * against a repo convention that every filesystem read inside a self-test is
 * cached. `renderedSource` could not be reused: it masks comments and strips
 * imports, which is wrong for a prose document.
 *
 * Keyed on root + path, like every other cache in this file. */
const textCache = new Map<string, string>();

export function sourceText(rel: string, root = REPO_ROOT): string {
  const key = root + '|' + rel;
  const hit = textCache.get(key);
  if (hit !== undefined) return hit;
  const text = readFileSync(join(root, rel), 'utf8');
  textCache.set(key, text);
  return text;
}

function walk(dir: string, root: string, out: string[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return; /* a root that does not exist is reported as drift, not a crash */
  }
  for (const name of entries) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!IGNORED_DIRS.has(name)) walk(full, root, out);
    }
    else out.push(relative(root, full).split(sep).join('/'));
  }
}

export interface ManifestDrift {
  unlisted: string[]; /* on disk, absent from the manifest */
  missing: string[]; /* in the manifest, absent from disk */
}

export function manifestDrift(actual: string[] = enumerateSourceFiles()): ManifestDrift {
  const listed = new Set(FILE_MANIFEST);
  const onDisk = new Set(actual);
  return {
    unlisted: actual.filter((p) => !listed.has(p)),
    missing: FILE_MANIFEST.filter((p) => !onDisk.has(p))
  };
}

