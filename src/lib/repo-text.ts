/* The repo's own text, read once: what every build-time check that reads the
 * repository reads through.
 *
 * The branch review against main (2026-10-21) found manifest-check.ts
 * changing for every reason any of its checks did, because it held all of
 * them. They live in modules grouped by what they read now, and this is the
 * layer they share: the walk over the manifest roots, the memoised file text,
 * the comment mask, the line scanner, the source set the gates sweep, the
 * markdown-table reader and the one list of audit-code shapes. Each was
 * moved here as it was, except that REPO_ROOT, walk,
 * pageCallsOutsideComments and renderedSource gained `export` (checks that
 * stayed in manifest-check.ts read them) and REPO_ROOT's comment names this
 * file.
 *
 * Build-time only. Imported by the check modules, which selftests.ts runs in
 * Node during `astro build` and under vitest; nothing in src/scripts/ imports
 * it, so node:fs never reaches a client bundle. NODE_FS_MODULES in
 * manifest-check.ts declares it with what it reads. */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/* src/lib/repo-text.ts -> repo root */
export const REPO_ROOT = fileURLToPath(new URL('../..', import.meta.url));

export const MANIFEST_ROOTS = ['src', 'tools', 'research'];

/* Not source, and regenerated by anyone who runs a tools/*.py generator, so
   listing it would make the manifest drift on every run. Mirrors .gitignore. */
const IGNORED_DIRS = new Set(['__pycache__']);

/* Memoised per root. These run inside self-tests, which vitest re-imports once
   per test file; without the cache the suite spends minutes re-walking the tree
   and re-reading a 119 KB catalog. */
const fileCache = new Map<string, string[]>();

export function enumerateSourceFiles(root = REPO_ROOT): string[] {
  const hit = fileCache.get(root);
  if (hit) return hit;
  const out: string[] = [];
  for (const dir of MANIFEST_ROOTS) walk(join(root, dir), root, out);
  out.sort();
  fileCache.set(root, out);
  return out;
}

/* Code review [§S9a]: the same memoisation, for raw file text.
 *
 * §S9a added twelve checks that read markdown and source as text, each with
 * its own `readFileSync`. Four of them re-read the same 20 KB methodology
 * note and two re-read the framework transcription, once per self-test pass,
 * against a repo convention that every filesystem read inside a self-test is
 * cached. `renderedSource` could not be reused: it masks comments and strips
 * imports, which is wrong for a prose document.
 *
 * Keyed on root + path, like every other cache in this file. */
const textCache = new Map<string, string>();

export function sourceText(rel: string, root = REPO_ROOT): string {
  const key = root + '|' + rel;
  const hit = textCache.get(key);
  if (hit !== undefined) return hit;
  const text = readFileSync(join(root, rel), 'utf8');
  textCache.set(key, text);
  return text;
}

export const AUDIT_CODE_IN_RENDERED_TEXT: [RegExp, string][] = [
  [/§/, 'a section sign'],
  [/\bR[0-9]{1,3}\b/, 'a recommendation number'],
  [/\bS[0-9]{1,2}[a-z]?\b/, 'a section number'],
  [/\bOI-[0-9]/, 'an open-items code'],
  [/\b(?:CP|BL|RB)-(?:\*|[A-Z]{2,4}\b|[0-9])/, 'an internal registry id'],
  [/[Aa]ppendix/, 'an appendix reference'],
  [/\b[Tt]able [0-9]/, 'a table number'],
  [/\b[Ss]ection [0-9]/, 'a section number']
];

export function walk(dir: string, root: string, out: string[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return; /* a root that does not exist is reported as drift, not a crash */
  }
  for (const name of entries) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!IGNORED_DIRS.has(name)) walk(full, root, out);
    }
    else out.push(relative(root, full).split(sep).join('/'));
  }
}

export interface CodeReference { file: string; line: number; text: string }

/* R21 [§S6a], after review: four source scans had copied the same eight lines -
   walk the tree, keep src/*.ts and *.astro, mask comments, test a global regex
   per line, reset lastIndex, push a CodeReference. The copies drifted in what
   they skipped, which is the part that matters. One scanner, and each caller
   says only what it is looking for and where it is allowed to be. */
export function scanSourceLines(
  pattern: RegExp,
  /* R171 [§S8]: `only` widened from one file to a list. A scan whose scope is
     a named set of narrative surfaces needs to say so as a set; passing them
     one at a time is how the four sites in RESIDUAL_CAVEAT_SITES would end up
     with four callers and three of them forgotten. */
  options: { skip?: string[]; only?: string | string[] } = {},
  root = REPO_ROOT
): CodeReference[] {
  const skip = new Set(options.skip || []);
  const only = options.only === undefined ? null
    : (typeof options.only === 'string' ? [options.only] : options.only);
  const files = only || enumerateSourceFiles(root);
  const out: CodeReference[] = [];
  for (const rel of files) {
    if (!rel.startsWith('src/')) continue;
    if (!rel.endsWith('.ts') && !rel.endsWith('.astro')) continue;
    if (skip.has(rel)) continue;
    const lines = maskComments(readFileSync(join(root, rel), 'utf8')).split('\n');
    lines.forEach((line, i) => {
      if (pattern.test(line)) out.push({ file: rel, line: i + 1, text: line.trim() });
      pattern.lastIndex = 0;
    });
  }
  return out;
}

export function maskComments(text: string): string {
  const out = text.split('');
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    const next = text[i + 1];
    if (c === '/' && next === '*') {
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) {
        if (text[i] !== '\n') out[i] = ' ';
        i += 1;
      }
      out[i] = ' '; out[i + 1] = ' ';
      i += 2;
      continue;
    }
    if (c === '/' && next === '/' && text[i - 1] !== ':') {
      while (i < text.length && text[i] !== '\n') { out[i] = ' '; i += 1; }
      continue;
    }
    if (c === '<' && text.startsWith('<!--', i)) {
      while (i < text.length && !text.startsWith('-->', i)) {
        if (text[i] !== '\n') out[i] = ' ';
        i += 1;
      }
      for (let k = 0; k < 3 && i + k < text.length; k += 1) out[i + k] = ' ';
      i += 3;
      continue;
    }
    i += 1;
  }
  return out.join('');
}

/* The branch review against main (2026-10-21): whether a page calls each of
 * these outside its comments. The six checks below read the raw page, so a
 * call moved into a comment passed every one of them. */
export function pageCallsOutsideComments(page: string, patterns: RegExp[], root: string): boolean {
  const text = maskComments(readFileSync(join(root, page), 'utf8'));
  return patterns.every((p) => p.test(text));
}

/* Import statements are stripped before the scan, and that is the whole check.
   The first version tested whether the identifier appeared anywhere in the
   file, and every site imports it - so deleting the render and leaving the
   import behind passed. Proven by the break refusing to fail: exactly the
   read-list defect the §S7 review caught, written again by the pass that had
   read about it. A mention is not a use. */
const IMPORT_STATEMENT = /import\s[\s\S]*?from\s*['"][^'"]*['"];?/g;

/* Review [§S8]: the mask-and-strip was written out three times, once per check
   that needed it. Memoised as well, because three checks now read the same
   handful of files on every build. */
const renderedCache = new Map<string, string>();

export function renderedSource(rel: string, root: string): string {
  const key = root + '|' + rel;
  const hit = renderedCache.get(key);
  if (hit !== undefined) return hit;
  const text = maskComments(readFileSync(join(root, rel), 'utf8'))
    .replace(IMPORT_STATEMENT, ' ');
  renderedCache.set(key, text);
  return text;
}

/* Code review [§S9c]: every markdown table in the file, as trimmed cells.
 *
 * §S9c matched rows with regexes that hard-coded a single space either side
 * of each pipe. Measured against the shipped file: padding the sweep table's
 * cells -- which is what every markdown formatter does -- turned all four
 * rows into "no published row", and one extra space in a region row did the
 * same. That is a FALSE FAILURE, and a check that produces false failures
 * gets loosened until it stops firing, which is how a real drift ships.
 *
 * Splitting on the pipe and trimming makes the check indifferent to
 * whitespace and to column alignment, which is the only thing about the
 * file's formatting a human should be free to change. */
/* Second code review [§S9c]: a placeholder no markdown cell can contain, so an
   escaped pipe survives the split and is put back afterwards. */
const ESCAPED_PIPE = '\u0000';

export function markdownRows(text: string): string[][] {
  const rows: string[][] = [];
  let fenced = false;
  for (const line of text.split('\n')) {
    const t = line.trim();
    /* A fenced block can hold anything, including a pipe-leading line. This
       very file has one, around the reproduce command. */
    if (t.startsWith('```')) { fenced = !fenced; continue; }
    if (fenced || !t.startsWith('|')) continue;
    /* `\|` inside a cell is an escaped pipe, not a column boundary. Splitting
       on it shifts every later cell, so the region table's population would be
       read out of the wrong column and reported as a drift that is not there.
       The audit's own recommendation table has six rows broken by exactly
       this, which is how the hazard is known. */
    const cells = t.replace(/^\|/, '').replace(/\|$/, '')
      .split('\\|').join(ESCAPED_PIPE)
      .split('|')
      .map((c) => c.split(ESCAPED_PIPE).join('|').trim());
    /* the |---|---| separator carries no content */
    if (cells.every((c) => /^:?-+:?$/.test(c))) continue;
    rows.push(cells);
  }
  return rows;
}

/* Prose, with every run of whitespace flattened, so re-wrapping a paragraph
   is not a drift. */
export function flowed(text: string): string {
  return text.replace(/\s+/g, ' ');
}

/* Single-line generated payloads. Reading them proves nothing here and costs
   about 600 KB per build; both are emitted by a generator and neither can hold
   a decorator. */
const GENERATED_PAYLOADS = new Set([
  'src/lib/quality-data.ts',
  'src/lib/data-phases.ts'
]);

/* Every .ts and .astro file under src/ that is worth scanning, exported so the
   vitest suite walks the same set rather than keeping its own copy. Review of
   P19 [S13]: it kept one, excluding the payloads by basename where this
   excludes them by path, which is how two copies of one rule start to
   disagree. */
export function sourceScanFiles(root = REPO_ROOT): string[] {
  const files: string[] = [];
  walk(join(root, 'src'), root, files);
  return files.filter((f) => /\.(ts|astro)$/.test(f) && !GENERATED_PAYLOADS.has(f));
}
